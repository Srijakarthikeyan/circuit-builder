import { PARTS } from './parts'
import { generateArduinoCode } from './codegen'

export function getComponentList(nodes = []) {
  const counts = new Map()

  nodes.forEach((node) => {
    const partKey = node.data?.partId || (PARTS[node.type] ? node.type : null) || node.id.split('-')[0]
    const part = PARTS[partKey]
    if (!part) return

    if (!counts.has(part.id)) {
      counts.set(part.id, {
        part,
        qty: 1,
        instances: [node.id],
      })
    } else {
      const entry = counts.get(part.id)
      entry.qty += 1
      entry.instances.push(node.id)
    }
  })

  return Array.from(counts.values())
}

export function getWiringTable(nodes = [], edges = []) {
  const nodeMap = new Map()
  nodes.forEach((n) => {
    const partKey = n.data?.partId || (PARTS[n.type] ? n.type : null) || n.id.split('-')[0]
    nodeMap.set(n.id, { node: n, part: PARTS[partKey] })
  })

  return edges.map((e, index) => {
    const srcInfo = nodeMap.get(e.source)
    const tgtInfo = nodeMap.get(e.target)

    const srcName = srcInfo?.part?.name ? `${srcInfo.part.name} (${e.source})` : e.source
    const tgtName = tgtInfo?.part?.name ? `${tgtInfo.part.name} (${e.target})` : e.target

    let purpose = 'Signal connection'
    if (e.sourceHandle === 'GND' || e.targetHandle === 'GND' || e.targetHandle === 'Cathode (-)' || e.targetHandle === 'Negative (-)') {
      purpose = 'Ground (0V Return)'
    } else if (e.sourceHandle === '3V3' || e.targetHandle === 'VCC' || e.sourceHandle === '5V') {
      purpose = `Power Supply (${e.sourceHandle || 'VCC'})`
    } else if (e.sourceHandle?.startsWith('GPIO') || e.targetHandle?.startsWith('GPIO')) {
      purpose = 'Digital / Analog GPIO Data'
    } else if (srcInfo?.part?.id === 'resistor' || tgtInfo?.part?.id === 'resistor') {
      purpose = 'Current-limiting series link'
    }

    return {
      id: e.id || `wire-${index + 1}`,
      from: `${srcName} : ${e.sourceHandle}`,
      to: `${tgtName} : ${e.targetHandle}`,
      purpose,
    }
  })
}

export function generateMarkdownGuide(nodes = [], edges = [], logicRules = [], issues = []) {
  const components = getComponentList(nodes)
  const wiring = getWiringTable(nodes, edges)
  const code = generateArduinoCode(nodes, edges, logicRules)
  const hasErrors = issues.some((i) => i.level === 'error')

  let md = `# Hardware-Software Project Build Guide\n\n`

  if (hasErrors) {
    md += `> ⚠️ **SAFETY WARNING**: This circuit currently contains electrical errors detected by the Circuit Builder validation rules. Review and fix all errors before assembling physical hardware to prevent equipment damage.\n\n`
  }

  md += `## 1. Bill of Materials (Component List)\n\n`
  md += `| Part Name | Qty | Operating Voltage | Typical Uses |\n`
  md += `| :--- | :---: | :--- | :--- |\n`
  components.forEach(({ part, qty }) => {
    md += `| **${part.name}** | ${qty} | ${part.operatingVoltage} | ${part.typicalUses} |\n`
  })
  md += `\n`

  md += `## 2. Point-to-Point Wiring Table\n\n`
  if (wiring.length === 0) {
    md += `*No wires have been connected on the canvas yet.*\n\n`
  } else {
    md += `| Wire # | From (Component & Pin) | To (Component & Pin) | Purpose |\n`
    md += `| :---: | :--- | :--- | :--- |\n`
    wiring.forEach((w, idx) => {
      md += `| ${idx + 1} | ${w.from} | ${w.to} | ${w.purpose} |\n`
    })
    md += `\n`
  }

  md += `## 3. Next Steps Checklist for Students\n\n`
  md += `- [ ] **Step 1 - Inspect & Procure Parts**: Ensure you have all components listed in the Bill of Materials above.\n`
  md += `- [ ] **Step 2 - Verify Voltages**: Confirm operating voltages (ESP32 pins are strictly 3.3V tolerant; 5V sensors like HC-SR04 ECHO require voltage division).\n`
  md += `- [ ] **Step 3 - UNPLUG USB Cable**: Always wire your breadboard and ESP32 with the power completely disconnected!\n`
  md += `- [ ] **Step 4 - Place Current-Limiting Resistors**: Ensure any LED has a 220Ω resistor placed in series with its Anode.\n`
  md += `- [ ] **Step 5 - Double Check with a Multimeter**: Use continuity / resistance mode to ensure 3.3V and GND are not shorted.\n`
  md += `- [ ] **Step 6 - Plug In and Upload Code**: Open Arduino IDE or PlatformIO, select "ESP32 Dev Module", and flash the generated code below.\n`
  md += `- [ ] **Step 7 - Open Serial Monitor**: Set baud rate to **115200 baud** to view real-time sensor output.\n\n`

  md += `## 4. Generated ESP32 Arduino Firmware\n\n`
  md += `\`\`\`cpp\n${code}\`\`\`\n\n`

  md += `---\n*Generated by Antigravity Circuit Builder*\n`

  return md
}
